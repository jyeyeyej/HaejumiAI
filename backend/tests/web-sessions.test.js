import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { createServer } from 'node:http';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { WebSessions } from '../src/adapters/filesystem/web-sessions.js';
import { createApiHandler } from '../src/adapters/node-http/transport.js';

const TOKEN = 'synthetic-local-token-000000000000000001';
const owner = 'synthetic-owner';
const serve = async (sessions) => {
  const auth = { async authenticate(header) { return header === `Bearer ${TOKEN}` ? { ownerId: owner } : null; } };
  const repositories = { state: { data: {} }, listOwnedProjects(id) { assert.equal(id, owner); return []; } };
  const server = createServer(createApiHandler({ repositories, auth, webSessions: sessions }));
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  return { base: `http://127.0.0.1:${server.address().port}`, close: () => new Promise((resolve) => server.close(resolve)) };
};

test('web cookie survives reload and server restart, blocks CSRF, expires, revokes and follows Bearer rotation', async (t) => {
  const dir = mkdtempSync(join(tmpdir(), 'haejumi-session-test-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const file = join(dir, 'sessions.json'); let now = 1_800_000_000_000;
  const options = { now: () => now, lifetimeSeconds: 60 };
  let sessions = new WebSessions(file, TOKEN, owner, options);
  let app = await serve(sessions);
  t.after(async () => { if (app) await app.close(); });
  const post = (headers = {}) => fetch(`${app.base}/api/v1/auth/web-session`, { method: 'POST', headers: { Origin: app.base, 'X-Haejumi-Web': '1', ...headers } });
  assert.equal((await post({ Authorization: 'Bearer wrong-token' })).status, 401);
  assert.equal((await post({ Authorization: `Bearer ${TOKEN}`, Origin: 'http://evil.example' })).status, 403);
  const login = await post({ Authorization: `Bearer ${TOKEN}` });
  assert.equal(login.status, 201);
  const cookie = login.headers.get('set-cookie');
  assert.match(cookie, /^haejumi_web=[A-Za-z0-9_-]{43}; HttpOnly; SameSite=Strict; Path=\/api\/v1; Max-Age=60/);
  assert.equal(cookie.includes(TOKEN), false);
  const id = cookie.split(';')[0];
  assert.equal(readFileSync(file, 'utf8').includes(id.split('=')[1]), false);
  const get = (extra = {}) => fetch(`${app.base}/api/v1/content/projects`, { headers: { Cookie: id, ...extra } });
  assert.equal((await get()).status, 200);
  assert.equal((await fetch(`${app.base}/api/v1/content/projects`, { headers: { Authorization: `Bearer ${TOKEN}` } })).status, 200);
  assert.equal((await get({ Origin: 'http://evil.example' })).status, 403);
  const logout = (extra = {}) => fetch(`${app.base}/api/v1/auth/web-session`, { method: 'DELETE', headers: { Cookie: id, Origin: app.base, 'X-Haejumi-Web': '1', ...extra } });
  assert.equal((await logout({ Origin: 'http://evil.example' })).status, 403);
  assert.equal((await logout({ 'X-Haejumi-Web': '0' })).status, 403);
  assert.equal((await fetch(`${app.base}/api/v1/backups`, { method: 'POST', headers: { Cookie: id, Origin: 'http://evil.example', 'X-Haejumi-Web': '1' } })).status, 403);
  assert.equal((await get()).status, 200);
  await app.close(); app = null;
  sessions = new WebSessions(file, TOKEN, owner, options);
  app = await serve(sessions);
  assert.equal((await get()).status, 200);
  assert.equal((await logout()).status, 204);
  assert.equal((await get()).status, 401);
  const next = await post({ Authorization: `Bearer ${TOKEN}` });
  const nextId = next.headers.get('set-cookie').split(';')[0];
  const nextGet = () => fetch(`${app.base}/api/v1/content/projects`, { headers: { Cookie: nextId } });
  assert.equal((await nextGet()).status, 200);
  now += 60_001;
  assert.equal((await nextGet()).status, 401);
  now -= 60_001;
  await app.close(); app = null;
  sessions = new WebSessions(file, 'replacement-token-00000000000000001', owner, options);
  app = await serve(sessions);
  assert.equal((await nextGet()).status, 401);
});
