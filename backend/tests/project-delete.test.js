import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createServer } from 'node:http';
import { JsonState } from '../src/adapters/filesystem/json-state.js';
import { LocalRepositories } from '../src/adapters/filesystem/repositories.js';
import { createApiHandler } from '../src/adapters/node-http/transport.js';

test('owned project deletion clears only its graph, preserves shared media and rejects stale/active requests', async (t) => {
  const dir = mkdtempSync(join(tmpdir(), 'haejumi-project-delete-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const state = new JsonState(join(dir, 'state.json'));
  const repo = new LocalRepositories({ state, dataDir: dir, maxMediaBytes: 1024 * 1024 });
  const owner = 'synthetic-owner';
  const other = 'other-owner';
  const sharedId = randomUUID();
  const extraId = randomUUID();
  for (const id of [sharedId, extraId]) state.data.media[id] = { mediaId: id, ownerId: owner, mediaType: 'image/jpeg', status: 'available', sha256: 'a'.repeat(64) };
  const target = repo.createForOwner(owner, { media_ids: [sharedId], target_seconds: 6 }, randomUUID());
  const kept = repo.createForOwner(owner, { media_ids: [sharedId, extraId], target_seconds: 8 }, randomUUID());
  state.data.llmBudget[owner] = { reserved_usd: 0.12 };
  state.data.privacyConsents[randomUUID()] = { owner_id: owner, status: 'active' };
  const checkpointId = Object.keys(state.data.checkpoints).find((id) => state.data.checkpoints[id].task_id === target.task_id);
  const approvalId = randomUUID(); const publicationId = randomUUID(); const jobId = randomUUID();
  state.data.approvals[approvalId] = { approval_id: approvalId, task_id: target.task_id, checkpoint_id: checkpointId };
  state.data.publications[publicationId] = { publication_id: publicationId, task_id: target.task_id, owner_id: owner };
  state.data.jobs[jobId] = { job_id: jobId, task_id: target.task_id, owner_id: owner, status: 'queued' };
  state.data.idempotency[`${owner}:approval:${randomUUID()}`] = { approvalId };
  state.save();
  const auth = { authenticate: async (header) => header === 'Bearer owner-token' ? { ownerId: owner } : header === 'Bearer other-token' ? { ownerId: other } : null };
  const server = createServer(createApiHandler({ repositories: repo, auth }));
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise((resolve) => server.close(resolve)));
  const url = `http://127.0.0.1:${server.address().port}/api/v1/content/projects/${target.project_id}`;
  const request = (token, body, key = randomUUID()) => fetch(url, { method: 'DELETE', headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json', 'idempotency-key': key }, body: JSON.stringify(body) });
  const input = { content_version: target.current_version, content_hash: target.content_hash };
  assert.equal((await request('other-token', input)).status, 404);
  assert.equal((await request('owner-token', { ...input, content_version: 99 })).status, 409);
  const busy = await request('owner-token', input);
  assert.equal(busy.status, 409);
  assert.equal((await busy.json()).error.code, 'RENDER_IN_PROGRESS');
  state.data.jobs[jobId].status = 'failed'; state.save();
  const completedJobId = randomUUID(); const cancelledJobId = randomUUID();
  state.data.jobs[completedJobId] = { job_id: completedJobId, task_id: target.task_id, owner_id: owner, status: 'succeeded' };
  state.data.jobs[cancelledJobId] = { job_id: cancelledJobId, task_id: target.task_id, owner_id: owner, status: 'cancelled' };
  state.data.approvals[approvalId].owner_id = other;
  assert.throws(() => repo.deleteOwnedProject(owner, target.project_id, input, randomUUID()), { code: 'INVALID_STATE_TRANSITION' });
  delete state.data.approvals[approvalId].owner_id;
  state.save();
  const originalSave = state.save.bind(state);
  state.save = () => { throw new Error('synthetic disk failure'); };
  assert.throws(() => repo.deleteOwnedProject(owner, target.project_id, input, randomUUID()), /synthetic disk failure/);
  state.save = originalSave;
  assert.ok(state.data.projects[target.project_id] && state.data.tasks[target.task_id] && state.data.jobs[jobId]);
  const key = randomUUID();
  const deleted = await request('owner-token', input, key);
  assert.equal(deleted.status, 200, await deleted.clone().text());
  assert.equal((await deleted.json()).media_preserved, true);
  assert.equal((await request('owner-token', input, key)).status, 200);
  assert.equal((await request('owner-token', input)).status, 404);
  assert.equal(repo.listOwnedProjects(owner).length, 1);
  assert.equal(repo.listOwnedProjects(owner)[0].project_id, kept.project_id);
  assert.ok(state.data.media[sharedId] && state.data.media[extraId]);
  assert.ok(state.data.llmBudget[owner]);
  assert.equal(Object.values(state.data.privacyConsents).length, 1);
  assert.ok(!state.data.tasks[target.task_id] && !state.data.jobs[jobId] && !state.data.jobs[completedJobId] && !state.data.jobs[cancelledJobId] && !state.data.approvals[approvalId] && !state.data.publications[publicationId]);
  assert.ok(Object.values(state.data.checkpoints).every((item) => item.task_id !== target.task_id));
  assert.ok(Object.values(state.data.idempotency).every((item) => item.approvalId !== approvalId));
  const recreated = repo.createForOwner(owner, { media_ids: [sharedId], target_seconds: 6 }, randomUUID());
  assert.notEqual(recreated.project_id, target.project_id);
});
